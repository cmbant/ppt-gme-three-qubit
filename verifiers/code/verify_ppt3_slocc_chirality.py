#!/usr/bin/env python3
"""Exact check of PPT THREE QUBIT cor:ppt3-chirality, part (b) (in family.tex, appendix_family.tex):
no invertible local filter maps R_s onto its complex conjugate, and the stabiliser of R_s in PGL_2(C)^{x3} is S_3.

  SC-1  B_s q_s(z) = (|0>+z|1>) x phi_s(z) with det phi_s(z) = -3 (z^2+s)^2 (symbolic in s, z): the A|BC product rays of
        R_s are P_inf=[v] and z in C, and phi_s(z) is a B|C product iff z = +-i sqrt(s).
  SC-2  B_s q_s(+-i sqrt s) = +-2i sqrt(s) (|0> +- i sqrt(s)|1>)^{x3} and (|0> +- i sqrt s|1>)^{x3} = u_s +- i sqrt(s)(w - s v):
        R_s contains exactly three fully product rays P_inf, P_+, P_-, spanning span(u_s,v,w).
  SC-3  the cyclic shift Pi has eigenvalue omega^2 exactly on span(e,o), eigenvalue omega on span(ebar,obar), and R_s and
        conj(R_s) meet the omega^2-eigenspace in dimension 2 and 0 (so a Pi-commuting F cannot map R_s to conj R_s).
  SC-4  S_3: the Moebius maps permuting {inf, +i sqrt s, -i sqrt s} give F^{x3} with F^{x3} R_s = R_s; six distinct elements.
"""
import itertools
import sympy as sp
from sympy.polys.matrices import DomainMatrix

s = sp.Symbol('s', positive=True)
z = sp.Symbol('z')
om = (-1 + sp.I * sp.sqrt(3)) / 2
omb = sp.conjugate(om)


def ket(b):
    v = sp.zeros(8, 1)
    v[int(b, 2)] = 1
    return v


def basis(sv):
    h = ket('011') + ket('101') + ket('110')
    return dict(u=ket('000') - sv * h, v=ket('111'), w=ket('001') + ket('010') + ket('100'),
                e=ket('011') + om * ket('101') + omb * ket('110'), o=ket('100') + om * ket('010') + omb * ket('001'))


def rk(m):
    return DomainMatrix.from_Matrix(sp.Matrix(m), extension=True).rank()


def main():
    b = basis(s)
    # SC-1
    U = 2 * z
    O = s + z**2
    W = z * U - O
    E = -z * O
    V = -s * z * U - z**2 * O
    p = (U * b['u'] + V * b['v'] + W * b['w'] + E * b['e'] + O * b['o']).applyfunc(sp.expand)
    M = sp.Matrix(2, 4, list(p))
    assert (M[1, :] - z * M[0, :]).applyfunc(sp.expand) == sp.zeros(1, 4)
    phi = sp.Matrix(2, 2, list(M[0, :]))
    assert sp.expand(phi.det() + 3 * (z**2 + s)**2) == 0
    print("SC-1 PASS: B_s q_s(z) = (|0>+z|1>) x phi_s(z), det phi_s(z) = -3(z^2+s)^2")
    # SC-2
    r = sp.sqrt(s)
    for sg in (1, -1):
        z0 = sg * sp.I * r
        cube = sp.kronecker_product(*[sp.Matrix([1, z0])] * 3)
        pz = p.subs(z, z0)
        assert (pz - 2 * z0 * cube).applyfunc(sp.expand) == sp.zeros(8, 1)
        assert (cube - (b['u'] + sg * sp.I * r * (b['w'] - s * b['v']))).applyfunc(sp.expand) == sp.zeros(8, 1)
    print("SC-2 PASS: the only fully product rays of R_s are [v] and [(|0> +- i sqrt(s)|1>)^3], spanning span(u_s,v,w)")
    # SC-3 (s = 1; the filter diag(1,sqrt s) maps R_1 to R_s and commutes with Pi)
    b1 = basis(1)
    Pi = sp.zeros(8, 8)
    for x in range(8):
        a, bb, c = (x >> 2) & 1, (x >> 1) & 1, x & 1
        Pi[(c << 2) | (a << 1) | bb, x] = 1
    ev = {k: Pi * b1[k] for k in 'euvwo'}
    assert (ev['e'] - omb * b1['e']).applyfunc(sp.simplify) == sp.zeros(8, 1) or (ev['e'] - om * b1['e']).applyfunc(sp.simplify) == sp.zeros(8, 1)
    lam_e = om if (ev['e'] - om * b1['e']).applyfunc(sp.simplify) == sp.zeros(8, 1) else omb
    for k in 'uvw':
        assert (ev[k] - b1[k]).applyfunc(sp.simplify) == sp.zeros(8, 1)
    assert (ev['o'] - lam_e * b1['o']).applyfunc(sp.simplify) == sp.zeros(8, 1)
    eig = Pi - lam_e * sp.eye(8)
    dim_eig = 8 - rk(eig)
    assert dim_eig == 2
    Rb = sp.Matrix.hstack(*[b1[k] for k in 'uvw'], b1['e'].applyfunc(sp.conjugate), b1['o'].applyfunc(sp.conjugate))
    # intersection of conj(R_1) with the lam_e eigenspace: dim = 5 + 2 - rank([conj(R) | eigenspace])
    esp = DomainMatrix.from_Matrix(eig, extension=True).nullspace().to_Matrix().T
    inter_conj = 5 + 2 - rk(sp.Matrix.hstack(Rb, esp))
    inter_R = 5 + 2 - rk(sp.Matrix.hstack(*[b1[k] for k in 'uvweo'], esp))
    assert (inter_R, inter_conj) == (2, 0), (inter_R, inter_conj)
    print("SC-3 PASS: Pi eigenspace of e,o is 2-dimensional; R_1 contains it, conj(R_1) meets it in 0")
    # SC-4: S_3 generated by the Moebius maps on {inf, i, -i} (s = 1); F^{x3} R_1 = R_1
    B1 = sp.Matrix.hstack(*[b1[k] for k in 'uvweo'])
    Kp = sp.Matrix.hstack(3 * ket('000') + ket('011') + ket('101') + ket('110'), b1['e'].applyfunc(sp.conjugate),
                          b1['o'].applyfunc(sp.conjugate)).H
    assert (Kp * B1).applyfunc(sp.simplify) == sp.zeros(3, 5)
    I = sp.I
    flip = sp.Matrix([[1, 0], [0, -1]])
    swap = sp.Matrix([[1, I], [-3 * I, -1]])
    pts = [sp.Matrix([0, 1]), sp.Matrix([1, I]), sp.Matrix([1, -I])]

    def perm(F):
        out = []
        for pt_ in pts:
            img = F * pt_
            hit = [k for k, q in enumerate(pts) if sp.simplify(img[0] * q[1] - img[1] * q[0]) == 0]
            assert len(hit) == 1
            out.append(hit[0])
        return tuple(out)

    for F in (flip, swap):
        F3 = sp.kronecker_product(F, F, F)
        assert (Kp * F3 * B1).applyfunc(sp.simplify) == sp.zeros(3, 5)
    perms = {perm(sp.eye(2))}
    frontier = [(sp.eye(2), perm(sp.eye(2)))]
    while frontier:
        F, pf = frontier.pop()
        for G in (flip, swap):
            H = (G * F).applyfunc(sp.simplify)
            ph = perm(H)
            if ph not in perms:
                perms.add(ph)
                frontier.append((H, ph))
    assert len(perms) == 6
    print("SC-4 PASS: F^{x3} R_1 = R_1 for the generators of the S_3 acting on {inf, i, -i}; the 6 permutations are realised")
    # (R_s = D^{x3} R_1 with D = diag(1, sqrt s): same statements for every s)
    for sv in (sp.Rational(1, 4), 4, 9):
        D = sp.diag(1, sp.sqrt(sv))
        D3 = sp.kronecker_product(D, D, D)
        Bs = sp.Matrix.hstack(*[basis(sv)[k] for k in 'uvweo'])
        assert rk(sp.Matrix.hstack(Bs, D3 * B1)) == 5
    print("SC-5 PASS: R_s = diag(1,sqrt s)^{x3} R_1 (s = 1/4, 4, 9)")
    print("ALL PASS")


if __name__ == '__main__':
    main()
